/**
 * Writes src/landing/glassbox.gen.json: the landing's "What Jev was asked" panel (D116). It runs the
 * browser gate's own steps (evidence extraction and compile(), src/lib/decision) over the pack
 * scenario refund-contradiction-flag on its route of config/policies.yaml, with the evaluator
 * templates of contracts/evaluators, for the decision model the cost assumptions price. The file is
 * committed: the landing ships no compiler, and a diff in review shows any change to what Jev is
 * asked. `--check` fails when the committed file is stale (WEB-LANDING's gate, make check).
 *
 *   node --import ./scripts/lib/aliasHooks.ts scripts/gen-landing-glassbox.ts [--check] [--out <file>]
 */
import './lib/aliasHooks.ts';

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { parse as parseYaml } from 'yaml';

const repo = fileURLToPath(new URL('../../', import.meta.url));
const web = fileURLToPath(new URL('../', import.meta.url));

/** The scenario the panel shows: the hero's refund example. */
const GLASSBOX_SCENARIO = 'refund-contradiction-flag';

const { values } = parseArgs({
  options: {
    check: { type: 'boolean', default: false },
    out: { type: 'string', default: join(web, 'src/landing/glassbox.gen.json') },
  },
});

const { compile, defaultBudget } = await import('../src/lib/decision/compile.ts');
const { decisionItems, extractEvidence } = await import('../src/lib/decision/evidence.ts');
const { resolveRoute, specMap } = await import('../src/lib/gate/route.ts');
const { compileRouteOf } = await import('../src/lib/gate/runner.ts');

const readJson = (path: string) => JSON.parse(readFileSync(path, 'utf8'));

interface PackScenario {
  id: string;
  route: string;
  api_format: string;
  request: unknown;
  response: string;
}

interface Question {
  type?: string;
  question?: string;
  instructions?: string;
  options?: Record<string, unknown>;
  criteria?: Record<string, { what?: string }>;
}

const pack = readJson(join(repo, 'contracts/demo/scenarios.v1.json')) as { scenarios: PackScenario[] };
const scenario = pack.scenarios.find((s) => s.id === GLASSBOX_SCENARIO);
if (!scenario) {
  console.error(`gen-landing-glassbox: contracts/demo/scenarios.v1.json has no scenario ${GLASSBOX_SCENARIO}`);
  process.exit(2);
}
const assumptions = readJson(join(repo, 'contracts/pricing/assumptions.v1.json')) as { prices: { decision_model: { match: string } } };
const model = assumptions.prices.decision_model.match.replaceAll('*', '');
const policy = parseYaml(readFileSync(join(repo, 'config/policies.yaml'), 'utf8'));
const templatesDir = join(repo, 'contracts/evaluators');
const templates = readdirSync(templatesDir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => readJson(join(templatesDir, f)));

const route = resolveRoute(policy, scenario.route);
const specs = specMap(templates);
const extraction = extractEvidence(scenario.api_format as Parameters<typeof extractEvidence>[0], scenario.request, route.evidence);
const evidence = decisionItems(extraction.items);
const compiled = compile(
  compileRouteOf(route, model),
  specs,
  {
    user_request: extraction.user_request,
    assistant_response: scenario.response,
    system_instructions: extraction.system_instructions,
    evidence,
    rules: {},
  },
  defaultBudget(),
);

/** One asked question, in the words the panel shows. */
function questionView(id: string): { id: string; evaluator: string; name: string; asks: string } {
  const ref = compiled.question_map[id];
  const spec = specs.get(ref);
  const body = (compiled.requests[compiled.qid_request[id]].questions[id] ?? {}) as Question;
  const asks = body.question ?? body.instructions ?? '';
  return { id, evaluator: ref, name: spec?.name ?? ref, asks };
}

const doc = {
  $comment: 'Generated by scripts/gen-landing-glassbox.ts (compile() over the pack scenario below). Do not edit: run the script.',
  scenario: scenario.id,
  route: scenario.route,
  model,
  calls: compiled.requests.length,
  est_tokens: compiled.est_tokens.reduce((a, n) => a + n, 0),
  evidence: evidence.map((e) => ({ id: e.id, source: e.source, text: e.text })),
  questions: Object.keys(compiled.question_map).map(questionView),
  requests: compiled.requests,
  request_sha256: compiled.request_sha256,
};
const text = `${JSON.stringify(doc, null, 2)}\n`;

if (values.check) {
  let committed = '';
  try {
    committed = readFileSync(values.out, 'utf8');
  } catch {
    // A missing file is stale.
  }
  if (committed !== text) {
    console.error(`${values.out} is stale: run \`node --import ./scripts/lib/aliasHooks.ts scripts/gen-landing-glassbox.ts\` and commit the result.`);
    process.exit(1);
  }
  console.log(`${values.out} is up to date (${doc.calls} call, ${doc.questions.length} questions).`);
} else {
  writeFileSync(values.out, text);
  console.log(`wrote ${values.out}: ${doc.calls} call, ${doc.questions.length} questions, about ${doc.est_tokens} tokens`);
}
