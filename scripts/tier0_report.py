#!/usr/bin/env python3
"""Publish the Tier-0 benchmark figures in docs/GATEWAY.md (D120, D167).

    scripts/tier0_report.py --gateway-md [--check] [--runs-dir docs/benchmarks/tier0] [--doc docs/GATEWAY.md]

reads the newest run in docs/benchmarks/tier0/ (raw `go test -bench` output, five counts, written by
`make bench-tier0-publish`, with `commit:` and `date:` lines) and writes, or with --check compares,
the block between `<!-- tier0:start -->` and `<!-- tier0:end -->`. Each figure is the median of the
counts' time per call, labelled measured (Go benchmark) with the CPU the run reports. Standard
library only.
"""

from __future__ import annotations

import argparse
import re
import statistics
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence

ROOT = Path(__file__).resolve().parents[1]
RUNS_DIR = ROOT / "docs" / "benchmarks" / "tier0"
DOC = ROOT / "docs" / "GATEWAY.md"
BLOCK_START = "<!-- tier0:start -->"
BLOCK_END = "<!-- tier0:end -->"

# The rows of the block: benchmark name (without the -N suffix), what it times, evidence, answer,
# and whether the budget statement covers it.
ROWS = (
    ("BenchmarkDetect/evidence=8k/answer=1k", "Instant checks", "8k tokens", "1k tokens", True),
    ("BenchmarkDetect/evidence=32k/answer=1k", "Instant checks", "32k tokens", "1k tokens", True),
    (
        "BenchmarkDetect/dense",
        "Instant checks, dense answer (a date, a link, a quotation and a citation in every sentence)",
        "32k tokens",
        "1k tokens",
        False,
    ),
    ("BenchmarkDetect/evidence=1MiB/answer=1k", "Instant checks", "1 MiB", "1k tokens", False),
    (
        "BenchmarkGatePreJev",
        "The gate around the fast check (instant checks, compile, decide, audit plan)",
        "8k tokens",
        "1k tokens",
        False,
    ),
)

BENCH_LINE = re.compile(r"^(Benchmark\S+?)(?:-\d+)?\s+\d+\s+([0-9.]+) ns/op\b")
CONFIG_LINE = re.compile(r"^([a-z][a-z0-9_-]*):\s*(.+?)\s*$")


class Refusal(Exception):
    """A run or document the report cannot use; the message says why."""


@dataclass
class Run:
    path: Path
    config: Dict[str, str] = field(default_factory=dict)
    ns_per_op: Dict[str, List[float]] = field(default_factory=dict)

    def median_ms(self, name: str) -> Optional[float]:
        values = self.ns_per_op.get(name)
        return statistics.median(values) / 1e6 if values else None


def parse_run(path: Path) -> Run:
    """A `go test -bench` output file: its key: value lines and every benchmark's ns/op."""
    run = Run(path)
    for line in path.read_text(encoding="utf-8").splitlines():
        m = BENCH_LINE.match(line)
        if m:
            run.ns_per_op.setdefault(m.group(1), []).append(float(m.group(2)))
            continue
        c = CONFIG_LINE.match(line)
        if c and c.group(1) not in run.config:
            run.config[c.group(1)] = c.group(2)
    for key in ("commit", "date", "cpu", "goos", "goarch"):
        if not run.config.get(key):
            raise Refusal(f"{path.name}: no `{key}:` line (make bench-tier0-publish writes it)")
    missing = [name for name, *_ in ROWS if name not in run.ns_per_op]
    if missing:
        raise Refusal(f"{path.name}: no figures for {', '.join(missing)}")
    return run


def newest_run(runs_dir: Path) -> Optional[Run]:
    """The run with the latest `date:` line, or None when none is published."""
    runs = [parse_run(p) for p in sorted(runs_dir.glob("*.txt"))] if runs_dir.is_dir() else []
    return max(runs, key=lambda r: r.config["date"], default=None)


def fmt_ms(value: float) -> str:
    if value < 1:
        return f"{value:.2f} ms"
    return f"{value:.1f} ms" if value < 100 else f"{value:.0f} ms"


def gateway_block(run: Optional[Run], root: Path = ROOT) -> str:
    """The block between the markers (markers excluded) for a run, or the placeholder."""
    if run is None:
        return (
            "No Tier-0 benchmark figures are published yet: `make bench-tier0-publish` runs the "
            "benchmarks and writes them here, labelled measured (Go benchmark, with the CPU they ran on)."
        )
    cfg = run.config
    counts = min(len(run.ns_per_op[name]) for name, *_ in ROWS)
    rel = run.path.resolve().relative_to(root.resolve()).as_posix()
    lines = [
        f"<!-- generated by scripts/tier0_report.py --gateway-md from {rel}; do not edit -->",
        f"**Measured** (Go benchmark, {cfg['cpu']}, {cfg['goos']}/{cfg['goarch']}"
        + (f", {cfg['go']}" if cfg.get("go") else "")
        + f") at `{cfg['commit']}` on {cfg['date'][:10]}: each figure is the median of {counts} runs' "
        "mean time per call, on the synthetic support documents and answers of "
        "`internal/gate/tier0_bench_test.go`. The budget statement covers the rows marked yes; the "
        "others are reported only.",
        "",
        "| What is timed | Evidence | Answer | Time per call | Budget statement |",
        "|---|---|---|---|---|",
    ]
    for name, what, evidence, answer, covered in ROWS:
        ms = run.median_ms(name)
        assert ms is not None  # parse_run refuses a run without it
        lines.append(
            f"| {what} | {evidence} | {answer} | {fmt_ms(ms)} | {'yes' if covered else 'reported only'} |"
        )
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    start, end = text.find(BLOCK_START), text.find(BLOCK_END)
    if start < 0 or end < 0 or end < start:
        raise Refusal(f"the document has no {BLOCK_START} ... {BLOCK_END} markers")
    return text[: start + len(BLOCK_START)] + "\n" + block + "\n" + text[end:]


def main(argv: Optional[Sequence[str]] = None, out=sys.stdout, err=sys.stderr) -> int:
    p = argparse.ArgumentParser(description="Publish the Tier-0 benchmark figures in GATEWAY.md.")
    p.add_argument("--gateway-md", action="store_true", required=True, help="write the GATEWAY.md block")
    p.add_argument("--check", action="store_true", help="compare the block instead of writing it")
    p.add_argument("--runs-dir", type=Path, default=RUNS_DIR)
    p.add_argument("--doc", type=Path, default=DOC)
    p.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    a = p.parse_args(argv)
    try:
        text = a.doc.read_text(encoding="utf-8")
        updated = replace_block(text, gateway_block(newest_run(a.runs_dir), a.root))
    except Refusal as e:
        print(f"tier0_report.py: {e}", file=err)
        return 2
    if a.check:
        if updated != text:
            print(
                f"tier0_report.py: the Tier-0 block of {a.doc} is out of date: run scripts/tier0_report.py --gateway-md",
                file=err,
            )
            return 1
        print(f"tier0_report.py: the Tier-0 block of {a.doc} is up to date", file=out)
        return 0
    if updated != text:
        a.doc.write_text(updated, encoding="utf-8")
    print(f"tier0_report.py: wrote the Tier-0 block of {a.doc}", file=out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
